def _build_user_prompt(schema: dict, text: str) -> str:
    fields_desc = "\n".join(f'  - "{k}": {v}' for k, v in schema.items())
    return (
        f"Extract the following fields from the bond prospectus text below.\n\n"
        f"Fields to extract:\n{fields_desc}\n\n"
        f"Return a JSON object with exactly these keys.\n\n"
        f"--- PROSPECTUS TEXT ---\n{text}"
    )


