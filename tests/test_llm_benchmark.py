# ---------------------------------------------------------------------------
# Result dataclass
# ---------------------------------------------------------------------------


@dataclass
class ScenarioResult:
    """Timing and quality metrics for one benchmark scenario."""

    scenario_id: str
    label: str
    context_chars: int
    latency_s: float = 0.0
    eval_count: int = 0
    eval_duration_s: float = 0.0
    tokens_per_sec: float = 0.0
    prompt_eval_count: int = 0
    prompt_eval_duration_s: float = 0.0
    valid_json: bool = False
    fields_returned: int = 0
    error: str = ""
    raw_response: str = ""


# ---------------------------------------------------------------------------
# HTTP call (direct, not via OllamaBackend so we capture raw metrics)
# ---------------------------------------------------------------------------


def _run_scenario(scenario: dict, base_url: str, model: str) -> ScenarioResult:
    result = ScenarioResult(
        scenario_id=scenario["id"],
        label=scenario["label"],
        context_chars=scenario["context_chars"],
    )

    user_prompt = _build_user_prompt(scenario["schema"], scenario["text"])
    payload = {
        "model": model,
        "messages": [
            {"role": "system", "content": _SYSTEM_PROMPT},
            {"role": "user", "content": user_prompt},
        ],
        "format": "json",
        "stream": False,
        "think": False,
        "options": {"temperature": 0.0, "num_ctx": 8192},
    }

    t0 = time.monotonic()
    try:
        response = httpx.post(
            f"{base_url}/api/chat",
            json=payload,
            timeout=620.0,
        )
        response.raise_for_status()
    except Exception as exc:
        result.error = str(exc)
        result.latency_s = time.monotonic() - t0
        return result

    result.latency_s = time.monotonic() - t0
    data = response.json()

    # Ollama timing fields (nanoseconds)
    result.eval_count = data.get("eval_count", 0)
    eval_ns = data.get("eval_duration", 0)
    result.eval_duration_s = eval_ns / 1e9
    if result.eval_duration_s > 0:
        result.tokens_per_sec = result.eval_count / result.eval_duration_s

    prompt_ns = data.get("prompt_eval_duration", 0)
    result.prompt_eval_duration_s = prompt_ns / 1e9
    result.prompt_eval_count = data.get("prompt_eval_count", 0)

    raw_text = data.get("message", {}).get("content", "")
    result.raw_response = raw_text[:500]

    try:
        parsed = json.loads(raw_text)
        result.valid_json = True
        result.fields_returned = sum(1 for v in parsed.values() if v is not None)
    except json.JSONDecodeError:
        pass

    return result


# ---------------------------------------------------------------------------
# Report writer
# ---------------------------------------------------------------------------


def _write_report(results: list[ScenarioResult], model: str, base_url: str) -> None:
    report_path = _report_path(model)
    report_path.parent.mkdir(parents=True, exist_ok=True)

    lines: list[str] = [
        "# LLM Benchmark Report",
        "",
        f"**Model:** `{model}`  ",
        f"**Ollama URL:** `{base_url}`  ",
        f"**Generated:** {time.strftime('%Y-%m-%d %H:%M:%S')}",
        "",
        "---",
        "",
        "## Results",
        "",
        "| Scenario | Context chars | Latency (s) | Tokens generated | Tokens/sec | Valid JSON | Fields returned | Error |",
        "|---|---|---|---|---|---|---|---|",
    ]

    for r in results:
        tps = f"{r.tokens_per_sec:.1f}" if r.tokens_per_sec > 0 else "—"
        err = r.error[:60] if r.error else "—"
        lines.append(
            f"| {r.label} | {r.context_chars:,} | {r.latency_s:.1f} | "
            f"{r.eval_count} | {tps} | {'✓' if r.valid_json else '✗'} | "
            f"{r.fields_returned} | {err} |"
        )

    # Summary stats
    successful = [r for r in results if r.valid_json]
    tps_values = [r.tokens_per_sec for r in results if r.tokens_per_sec > 0]
    avg_tps = sum(tps_values) / len(tps_values) if tps_values else 0

    lines += [
        "",
        "---",
        "",
        "## Summary",
        "",
        f"- Scenarios completed successfully: **{len(successful)} / {len(results)}**",
        f"- Average generation speed: **{avg_tps:.1f} tokens/sec**",
        f"- Fastest scenario: **{min(results, key=lambda r: r.latency_s).label}** "
        f"({min(r.latency_s for r in results):.1f}s)",
        f"- Slowest scenario: **{max(results, key=lambda r: r.latency_s).label}** "
        f"({max(r.latency_s for r in results):.1f}s)",
        "",
        "---",
        "",
        "## Reference Benchmarks (community-reported, tokens/sec)",
        "",
        "These are approximate generation speeds reported by the Ollama community",
        "for comparable models on Apple Silicon. Use them to assess whether your",
        "hardware is performing as expected.",
        "",
        "| Setup | Tokens/sec |",
        "|---|---|",
    ]

    for setup, tps in REFERENCE_BENCHMARKS.items():
        marker = " ← **your result is here**" if avg_tps > 0 and abs(avg_tps - tps) == min(
            abs(avg_tps - v) for v in REFERENCE_BENCHMARKS.values()
        ) else ""
        lines.append(f"| {setup} | ~{tps}{marker} |")

    lines += [
        "",
        f"**Your average: {avg_tps:.1f} tok/s**",
        "",
        "---",
        "",
        "## Interpretation",
        "",
    ]

    if avg_tps == 0:
        lines += [
            "All scenarios failed or timed out. Check that Ollama is running and the model is pulled.",
            "",
            "```",
            "ollama list          # confirm model is present",
            "curl http://localhost:11434  # confirm Ollama is running",
            "```",
        ]
    elif avg_tps < 5:
        lines += [
            f"**Very slow ({avg_tps:.1f} tok/s).** Likely causes:",
            "- Model running entirely on CPU (no GPU/Metal acceleration)",
            "- Available RAM is insufficient — model is swapping to disk",
            "- Try a smaller model: `ollama pull phi3.5` (~2.2 GB, ~55 tok/s on M2 Pro)",
            "- Or switch to a text-only model: `ollama pull qwen2.5:7b` (~4.7 GB, ~35 tok/s on M2 Pro)",
        ]
    elif avg_tps < 15:
        lines += [
            f"**Slow ({avg_tps:.1f} tok/s).** The pipeline will work but extractions take several minutes.",
            "- Consider a lighter model for faster iteration: `ollama pull qwen2.5:7b`",
            "- If on Apple Silicon, ensure Ollama has Metal access (check Activity Monitor → GPU)",
        ]
    elif avg_tps < 40:
        lines += [
            f"**Acceptable ({avg_tps:.1f} tok/s).** Extractions will take 1–3 minutes per bond.",
            "This is typical for a 7–8B model on M2 Pro / M3 hardware.",
        ]
    else:
        lines += [
            f"**Good ({avg_tps:.1f} tok/s).** Extractions will complete in under a minute per bond.",
        ]

    # Raw responses
    lines += [
        "",
        "---",
        "",
        "## Raw model responses (first 500 chars per scenario)",
        "",
    ]
    for r in results:
        lines += [
            f"### {r.label}",
            "",
            f"```json",
            r.raw_response if r.raw_response else "(empty — error or timeout)",
            "```",
            "",
        ]

    report_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"\nReport written to: {report_path}")


