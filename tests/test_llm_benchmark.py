"""
LLM Speed and Performance Benchmark.

Runs the configured Ollama model through four scenarios with increasing
context size and extraction difficulty.  Writes a Markdown report to
data/output/debug/llm_benchmark_report.md for human review.

Run with:
    .venv/bin/python -m pytest tests/test_llm_benchmark.py -v -s

The -s flag lets timing output stream to the console while the test runs.
Results are always written to the report file regardless of pass/fail.

Scenarios
---------
1. Tiny context   / Easy task   — ~200 chars, extract 1 field (ISIN)
2. Tiny context   / Hard task   — ~200 chars, extract 7 fields with enums
3. Large context  / Easy task   — ~5000 chars, extract 1 field (ISIN)
4. Large context  / Hard task   — ~5000 chars, extract 7 fields with enums

Metrics collected per call (from Ollama response headers):
    latency_s        wall-clock seconds for the HTTP round-trip
    eval_count       tokens generated by the model
    eval_duration_s  model inference time in seconds (excludes prompt eval)
    tokens_per_sec   eval_count / eval_duration_s  (generation speed)
    valid_json       whether the response parsed as valid JSON
    fields_returned  number of non-null fields in the JSON response
"""

